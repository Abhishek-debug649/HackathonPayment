const express = require('express');
const router = express.Router();
const multer = require('multer');
const { CloudinaryStorage } = require('multer-storage-cloudinary');
const cloudinary = require('cloudinary').v2;
const Student = require('../models/Student');

// Configure Cloudinary
cloudinary.config({
    cloud_name: process.env.CLOUDINARY_CLOUD_NAME,
    api_key: process.env.CLOUDINARY_API_KEY,
    api_secret: process.env.CLOUDINARY_API_SECRET,
});

// Configure Multer Storage with Cloudinary
const storage = new CloudinaryStorage({
    cloudinary: cloudinary,
    params: {
        folder: 'hackathon_payments',
        allowed_formats: ['jpg', 'png', 'jpeg'],
    },
});

const upload = multer({
    storage: storage,
    limits: { fileSize: 5 * 1024 * 1024 } // 5MB limit
});

// @route POST /api/verify
// @desc Verify student using email and uniqueCode
router.post('/verify', async (req, res) => {
    console.log('--- VERIFY REQUEST RECEIVED ---');
    console.log('Body:', req.body);
    try {
        const { email, uniqueCode } = req.body;

        if (!email || !uniqueCode) {
            console.log('Missing fields');
            return res.status(400).json({ success: false, message: 'Email and Unique Code are required' });
        }

        console.log('Querying DB for:', email, uniqueCode);
        const student = await Student.findOne({ email, uniqueCode });
        console.log('DB result:', student ? 'Found' : 'Not Found');

        if (!student) {
            return res.status(401).json({ success: false, message: 'Invalid Email or Unique Code' });
        }

        const payload = {
            success: true,
            student: {
                name: student.name,
                teamName: student.teamName,
                studentId: student.studentId,
                paymentSubmitted: student.paymentSubmitted,
                email: student.email,
                uniqueCode: student.uniqueCode
            }
        };
        console.log('Sending payload:', payload);
        res.json(payload);

    } catch (error) {
        console.log('--- ERROR IN VERIFY ---');
        console.log(error);
        console.error('Verify error stack:', error.stack);
        res.status(500).json({ success: false, message: 'Server error during verification' });
    }
});

// @route POST /api/submit-payment
// @desc Submit payment details and screenshot
router.post('/submit-payment', upload.single('screenshot'), async (req, res) => {
    try {
        const { email, uniqueCode, utr } = req.body;

        if (!email || !uniqueCode || !utr) {
            return res.status(400).json({ success: false, message: 'Missing required fields' });
        }

        // Verify student again
        const student = await Student.findOne({ email, uniqueCode });

        if (!student) {
            return res.status(401).json({ success: false, message: 'Unauthorized student' });
        }

        // Check if payment already submitted to prevent duplicate
        if (student.paymentSubmitted) {
            return res.status(400).json({ success: false, message: 'Payment already submitted' });
        }

        // Ensure image was uploaded
        if (!req.file) {
            return res.status(400).json({ success: false, message: 'Screenshot is required' });
        }

        // The image URL generated by Cloudinary
        const screenshotUrl = req.file.path;

        // Update student record
        student.utrCode = utr;
        student.screenshotUrl = screenshotUrl;
        student.paymentSubmitted = true;

        await student.save();

        res.json({
            success: true,
            message: 'Payment successfully recorded',
        });

    } catch (error) {
        console.error('Submit payment error:', error);
        res.status(500).json({ success: false, message: 'Server error during payment submission' });
    }
});

