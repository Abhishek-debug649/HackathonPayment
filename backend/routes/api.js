// ==================== HOST ROUTES ====================

// @route POST /api/host-login
// @desc Authenticate host with hardcoded credentials
router.post('/host-login', (req, res) => {
    try {
        const { email, password } = req.body;

        if (!email || !password) {
            return res.status(400).json({ success: false, message: 'Email and password are required' });
        }

        const hostEmail = process.env.HOST_EMAIL;
        const hostPassword = process.env.HOST_PASSWORD;

        if (email === hostEmail && password === hostPassword) {
            return res.json({
                success: true,
                message: 'Host authenticated successfully',
                host: { email: hostEmail }
            });
        }

        return res.status(401).json({ success: false, message: 'Invalid host credentials' });
    } catch (error) {
        console.error('Host login error:', error);
        res.status(500).json({ success: false, message: 'Server error during host login' });
    }
});

// @route GET /api/host/students
// @desc Get all students sorted by approval status (pending first, then verified, then rejected)
router.get('/host/students', async (req, res) => {
    try {
        const students = await Student.find({}, '-__v').lean();

        // Custom sort: pending → verified → rejected
        const statusOrder = { pending: 0, verified: 1, rejected: 2 };
        students.sort((a, b) => {
            const orderA = statusOrder[a.isApproved] ?? 3;
            const orderB = statusOrder[b.isApproved] ?? 3;
            if (orderA !== orderB) return orderA - orderB;
            // Secondary sort by newest first
            return new Date(b.createdAt) - new Date(a.createdAt);
        });

        res.json({ success: true, students });
    } catch (error) {
        console.error('Host students error:', error);
        res.status(500).json({ success: false, message: 'Server error' });
    }
});

// @route PUT /api/host/student/:id/status
// @desc Update student isApproved status
router.put('/host/student/:id/status', async (req, res) => {
    try {
        const { id } = req.params;
        const { status } = req.body;

        if (!['pending', 'verified', 'rejected'].includes(status)) {
            return res.status(400).json({ success: false, message: 'Invalid status. Must be pending, verified, or rejected.' });
        }

        const student = await Student.findByIdAndUpdate(
            id,
            { isApproved: status },
            { new: true }
        );

        if (!student) {
            return res.status(404).json({ success: false, message: 'Student not found' });
        }

        res.json({ success: true, message: `Student status updated to ${status}`, student });
    } catch (error) {
        console.error('Update status error:', error);
        res.status(500).json({ success: false, message: 'Server error' });
    }
});

module.exports = router;
